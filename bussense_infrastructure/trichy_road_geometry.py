def haversine_m(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    """Calculates spherical distance between two points in meters."""
    R = 6371000.0
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dp, dl = math.radians(lat2 - lat1), math.radians(lon2 - lon1)
    a = math.sin(dp / 2.0)**2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2.0)**2
    return float(R * 2.0 * math.atan2(math.sqrt(a), math.sqrt(1.0 - a)))


def compute_bearing_deg(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    """Calculates initial compass bearing from (lat1, lon1) to (lat2, lon2) in degrees [0, 360)."""
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dl = math.radians(lon2 - lon1)
    x = math.sin(dl) * math.cos(p2)
    y = math.cos(p1) * math.sin(p2) - math.sin(p1) * math.cos(p2) * math.cos(dl)
    bearing = math.degrees(math.atan2(x, y))
    return float((bearing + 360.0) % 360.0)


def point_to_segment_distance_m(
    plat: float, plon: float,
    alat: float, alon: float,
    blat: float, blon: float
) -> float:
    """Computes minimum distance from point P to line segment AB in meters."""
    ab_dist = haversine_m(alat, alon, blat, blon)
    if ab_dist < 1e-4:
        return haversine_m(plat, plon, alat, alon)

    # Convert to local Cartesian approximation (meters)
    cos_lat = math.cos(math.radians(alat))
    m_per_deg_lat = 111320.0
    m_per_deg_lon = 111320.0 * cos_lat

    ax, ay = alon * m_per_deg_lon, alat * m_per_deg_lat
    bx, by = blon * m_per_deg_lon, blat * m_per_deg_lat
    px, py = plon * m_per_deg_lon, plat * m_per_deg_lat

    dx, dy = bx - ax, by - ay
    seg_len_sq = dx*dx + dy*dy
    if seg_len_sq == 0:
        return math.hypot(px - ax, py - ay)

    # Projection factor t
    t = max(0.0, min(1.0, ((px - ax)*dx + (py - ay)*dy) / seg_len_sq))
    proj_x = ax + t * dx
    proj_y = ay + t * dy

    return float(math.hypot(px - proj_x, py - proj_y))


class TrichyRoadGeometryManager:
    """
    Manages the locked OSM road polyline, distance-along-road sampling,
    and strict GPS tolerance assertions.
    """

    ROAD_NAME = "Bharathidasan Salai"
    OSM_WAY_ID = 369881223
    ROAD_SEGMENT_ID = "SEG-TRICHY-BHARATHIDASAN-01"

    def __init__(self, sampling_interval_m: float = 5.0, tolerance_m: float = 10.0):
        self.sampling_interval_m = sampling_interval_m
        self.tolerance_m = tolerance_m
        self.raw_nodes = BHARATHIDASAN_SALAI_OSM_NODES
        self.polyline_coords = [(n["lat"], n["lon"]) for n in self.raw_nodes]

        # Calculate cumulative distance along polyline nodes
        self.cumulative_distances = [0.0]
        for i in range(len(self.polyline_coords) - 1):
            p1 = self.polyline_coords[i]
            p2 = self.polyline_coords[i + 1]
            seg_len = haversine_m(p1[0], p1[1], p2[0], p2[1])
            self.cumulative_distances.append(self.cumulative_distances[-1] + seg_len)

        self.total_road_length_m = self.cumulative_distances[-1]

    def sample_point_at_distance(self, dist_m: float) -> Tuple[float, float, float]:
        """
        Samples a point at exact arc length distance along the real road polyline.
        Returns: (latitude, longitude, heading_deg)
        """
        dist_m = max(0.0, min(self.total_road_length_m, dist_m))

        # Find segment containing this distance
        seg_idx = 0
        while seg_idx < len(self.cumulative_distances) - 2 and self.cumulative_distances[seg_idx + 1] < dist_m:
            seg_idx += 1

        d0 = self.cumulative_distances[seg_idx]
        d1 = self.cumulative_distances[seg_idx + 1]
        seg_len = d1 - d0

        fraction = (dist_m - d0) / seg_len if seg_len > 0 else 0.0

        p1 = self.polyline_coords[seg_idx]
        p2 = self.polyline_coords[seg_idx + 1]

        lat = p1[0] + fraction * (p2[0] - p1[0])
        lon = p1[1] + fraction * (p2[1] - p1[1])

        heading = compute_bearing_deg(p1[0], p1[1], p2[0], p2[1])
        return lat, lon, heading

    def validate_point_on_road(self, lat: float, lon: float) -> Dict[str, Any]:
        """
        Strict GPS Road Validation (Section 23.7).
        Calculates distance from coordinate to road centerline polyline.
        Asserts distance <= tolerance_m (10m).
        """
        min_dist = float("inf")
        closest_seg = 0

        for i in range(len(self.polyline_coords) - 1):
            p1 = self.polyline_coords[i]
            p2 = self.polyline_coords[i + 1]
            d = point_to_segment_distance_m(lat, lon, p1[0], p1[1], p2[0], p2[1])
            if d < min_dist:
                min_dist = d
                closest_seg = i

        is_valid = (min_dist <= self.tolerance_m)

        return {
            "valid": is_valid,
            "distance_to_centerline_m": round(min_dist, 3),
            "road_name": self.ROAD_NAME,
            "osm_way_id": self.OSM_WAY_ID,
            "segment_id": self.ROAD_SEGMENT_ID,
            "closest_segment_index": closest_seg
        }

    def generate_full_bus_trajectory(
        self,
        bus_id: str = "BUS_DEMO_001",
        speed_kmh: float = 25.0,
        start_time: float = 0.0
    ) -> List[Dict[str, Any]]:
        """
        Generates bus trajectory points sampled along the actual road polyline.
        Every point is verified by validate_point_on_road().
        Fails loudly if any point leaves road tolerance.
        """
        points = []
        speed_mps = (speed_kmh * 1000.0) / 3600.0
        dt = self.sampling_interval_m / speed_mps

        num_steps = int(math.ceil(self.total_road_length_m / self.sampling_interval_m))

        for step in range(num_steps + 1):
            dist_m = min(self.total_road_length_m, step * self.sampling_interval_m)
            lat, lon, heading = self.sample_point_at_distance(dist_m)
            t = start_time + step * dt

            val = self.validate_point_on_road(lat, lon)
            if not val["valid"]:
                raise ValueError(
                    f"CRITICAL DEMO FAILURE: Point at dist={dist_m:.1f}m ({lat:.6f}, {lon:.6f}) "
                    f"is {val['distance_to_centerline_m']:.2f}m from centerline (> {self.tolerance_m}m tolerance)!"
                )

            points.append({
                "bus_id": bus_id,
                "timestamp": round(t, 2),
                "latitude": round(lat, 7),
                "longitude": round(lon, 7),
                "heading": round(heading, 1),
                "road_name": self.ROAD_NAME,
                "osm_way_id": self.OSM_WAY_ID,
                "road_segment_id": self.ROAD_SEGMENT_ID,
                "distance_along_road_m": round(dist_m, 2),
                "distance_to_centerline_m": val["distance_to_centerline_m"],
                "speed_kmh": speed_kmh,
                "simulation_mode": True
            })

        return points

